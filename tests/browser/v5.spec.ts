import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('real V5 text, upper window, save/restore, undo and restart without fictional automap', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Load story file').setInputFiles('public/fixtures/survey.z5')
  const input = page.getByLabel('Story command')
  const transcript = page.getByLabel('Story transcript')
  async function command(text: string) {
    await expect(input).toBeEnabled()
    await input.fill(text)
    await input.press('Enter')
    await expect(input).toBeEnabled()
  }
  await expect(input).toBeEnabled()
  await expect(page.getByLabel('Story upper window')).toHaveText('upper telemetry')
  await expect(page.locator('.map-empty')).toContainText('Automatic mapping is supported for V1-V3 only.')
  await expect(transcript).toContainText('foyer')
  await command('north')
  await expect(transcript).toContainText('you walk north\ngarden')
  const saved = page.waitForEvent('download')
  await command('save')
  const download = await saved
  const bytes = await readFile((await download.path())!)
  expect(bytes.subarray(0, 4).toString()).toBe('FORM')
  await command('south')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(input).toBeEnabled()
  await expect(transcript).toContainText('Undo one turn\ngarden')
  await command('south')
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Choose save file' })).toBeVisible()
  await page.getByLabel('Restore save file').setInputFiles({ name: 'v5.qzl', mimeType: 'application/octet-stream', buffer: bytes })
  await expect(input).toBeEnabled()
  await expect(transcript).toContainText('save checkpoint reached\ngarden')
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel restore' }).click()
  await expect(input).toBeEnabled()
  await page.getByRole('button', { name: 'Restart', exact: true }).click()
  await page.getByRole('button', { name: 'Restart story', exact: true }).click()
  await expect(input).toBeEnabled()
  await expect(transcript).not.toContainText('you walk north')
  await expect(page.locator('.map-panel .panel-heading')).toContainText('000 NODES')
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('V5 timed input reports the specific unsupported capability, not ExitStatus', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Load story file').setInputFiles('public/fixtures/timed.z5')
  await expect(page.getByRole('alert')).toContainText('Timed input is not supported in the browser host')
  await expect(page.getByRole('alert')).not.toContainText('ExitStatus')
  await expect(page.getByLabel('Story command')).toBeDisabled()
  await page.getByRole('button', { name: 'Restart', exact: true }).click()
  await page.getByRole('button', { name: 'Keep exploring' }).click()
})
