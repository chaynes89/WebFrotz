import { expect, test } from '@playwright/test'

for (const version of [1, 2, 3, 5]) {
  test(`V${version} Help hides spoilers until revealed and preserves pending gameplay`, async ({ page }) => {
    await page.goto('/')
    await page.getByLabel('Load story file').setInputFiles(`public/fixtures/survey.z${version}`)
    const input = page.getByLabel('Story command')
    await expect(input).toBeEnabled()
    await input.fill('north')
    const transcript = await page.getByLabel('Story transcript').textContent()
    const nodes = await page.locator('.map-panel .panel-heading').textContent()
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    const help = page.getByRole('dialog', { name: 'Command help' })
    await expect(help).toBeVisible()
    await expect(help).toContainText('unlock door with key')
    await expect(help.getByRole('button', { name: 'Close help' })).toBeFocused()
    await expect(help.getByRole('list', { name: 'Story dictionary keys' })).toHaveCount(0)
    await expect(help).toContainText('Spoiler warning')
    await help.getByRole('button', { name: 'Reveal story vocabulary (spoilers)' }).click()
    const words = help.getByRole('list', { name: 'Story dictionary keys' })
    await expect(words.getByRole('listitem')).toHaveText(['garden', 'lamp', version === 5 ? 'lighthous' : 'lighth', 'north', 'secret', 'south'])
    await expect(help).toContainText('Dictionary words do not guarantee a phrase works.')
    await page.keyboard.press('Escape')
    await expect(help).not.toBeVisible()
    await expect(page.getByRole('button', { name: 'Help', exact: true })).toBeFocused()
    expect(await page.getByLabel('Story transcript').textContent()).toBe(transcript)
    expect(await page.locator('.map-panel .panel-heading').textContent()).toBe(nodes)
    await expect(input).toHaveValue('north')
    await page.getByRole('button', { name: 'Help', exact: true }).click()
    await expect(help.getByRole('list', { name: 'Story dictionary keys' })).toHaveCount(0)
    await help.getByRole('button', { name: 'Close help' }).click()
    await input.press('Enter')
    await expect(page.getByLabel('Story transcript')).toContainText('you walk north')
  })
}

test('Help before loading and on narrow screens, with malformed vocabulary isolated from gameplay', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Command help' })
  await expect(help).toContainText('Load a supported')
  await expect(help.getByRole('button', { name: 'Reveal story vocabulary (spoilers)' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await help.getByRole('button', { name: 'Close help' }).click()
  const response = await page.request.get(new URL('fixtures/survey.z3', page.url()).href)
  expect(response.ok()).toBe(true)
  const buffer = await response.body()
  buffer.writeInt16BE(32767, 0x482)
  await page.getByLabel('Load story file').setInputFiles({ name: 'malformed.z3', mimeType: 'application/octet-stream', buffer })
  await expect(page.getByLabel('Story command')).toBeEnabled()
  await page.getByRole('button', { name: 'Help', exact: true }).click()
  await help.getByRole('button', { name: 'Reveal story vocabulary (spoilers)' }).click()
  await expect(help.getByRole('alert')).toContainText('out-of-range')
  await help.getByRole('button', { name: 'Close help' }).click()
  await page.getByLabel('Story command').fill('north')
  await page.getByLabel('Story command').press('Enter')
  await expect(page.getByLabel('Story transcript')).toContainText('you walk north')
})
